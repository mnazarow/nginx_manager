def apply(models) -> None:
    for model in models:
        name = model.__name__
        for key, f in model.model_fields.items():
            item = D.get(f"{name}.{key}")
            if not item:
                continue
            extra = f.json_schema_extra
            if not isinstance(extra, dict):
                extra = {}
                f.json_schema_extra = extra
            doc, rec, example = item
            if doc and not extra.get("doc"):
                extra["doc"] = doc
            if rec and not extra.get("rec"):
                extra["rec"] = rec
            if example and not extra.get("example"):
                extra["example"] = example
