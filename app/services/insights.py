def assess(metric: str, value: Optional[float], requests: Optional[int] = None,
           extra: Optional[Dict[str, Any]] = None) -> str:
    """Уровень показателя по порогам METRICS (используется сервером; браузер считает так же)."""
    m = METRICS.get(metric)
    if not m or value is None or not m.get("dir"):
        return "ok"
    if m.get("min_req") and requests is not None and requests < m["min_req"]:
        return "ok"
    warn, crit = m.get("warn"), m.get("crit")
    if extra and "capacity" in extra and m.get("warn_ratio"):
        warn, crit = extra["capacity"] * m["warn_ratio"], extra["capacity"] * m["crit_ratio"]
    if warn is None:
        return "ok"
    if m["dir"] == "above":
        return "crit" if crit is not None and value >= crit else "warn" if value >= warn else "ok"
    return "crit" if crit is not None and value <= crit else "warn" if value <= warn else "ok"


