SCENARIOS: Dict[str, Scenario] = {s.id: s for s in S}


def scenario_dict(s: Scenario) -> Dict[str, Any]:
    return {"id": s.id, "group": s.group, "group_title": GROUP_TITLES[s.group], "title": s.title, "when": s.when,
            "what": s.what, "causes": s.causes, "actions": s.actions,
            "links": [{"label": a, "href": b} for a, b in s.links], "doc": {"page": s.doc[0], "section": s.doc[1]}}


# =============================================================================
#  Анализ
# =============================================================================
class Analyzer:
    CACHE_TTL = 15.0

    def __init__(self, app) -> None:
        self.app = app
        self._cache: Dict[tuple, Tuple[float, Dict[str, Any]]] = {}
        self.first_seen: Dict[str, float] = {}
        self.last: Dict[str, Any] = {"counts": {"crit": 0, "warn": 0, "info": 0}, "findings": [], "ts": 0}

    # ---------------------------------------------------------------- каталог
    def capacity(self) -> int:
        g = self.app.global_settings()
        try:
            workers = int(g.worker_processes)
        except (TypeError, ValueError):
            import os
            workers = os.cpu_count() or 1
        return max(1, int(g.worker_connections) * workers // 2)

    def catalog(self) -> Dict[str, Any]:
        metrics = {k: {kk: vv for kk, vv in v.items() if kk != "doc"} | {"doc": {"page": v["doc"][0],
                                                                                   "section": v["doc"][1]}}
                   for k, v in METRICS.items()}
        cap = self.capacity()
        metrics["connections"]["warn"] = round(cap * METRICS["connections"]["warn_ratio"])
        metrics["connections"]["crit"] = round(cap * METRICS["connections"]["crit_ratio"])
        metrics["connections"]["capacity"] = cap
        return {"metrics": metrics, "levels": LEVEL_LABELS,
                "groups": [{"id": g, "title": t} for g, t in GROUPS],
                "scenarios": [scenario_dict(s) for s in S], "muted": list(self.app.panel().insights_muted)}

    # ---------------------------------------------------------------- данные
    def _baseline(self, site: str, start: float) -> Optional[Dict[str, Any]]:
        """Сутки до начала периода по почасовой статистике: среднее rps и перцентили."""
        rows = self.app.db.query("SELECT req, rt_sum, data FROM stats_hour WHERE site=? AND ts>=? AND ts<?",
                                 (site, int(start) - 86400, int(start) // 3600 * 3600))
        if not rows:
            return None
        req = sum(r["req"] for r in rows)
        hist = [0] * NB
        for r in rows:
            h = (json.loads(r["data"] or "{}")).get("hist") or []
            for i, v in enumerate(h[:NB]):
                hist[i] += v
        return {"hours": len(rows), "req": req, "rps": req / (len(rows) * 3600), "p95": percentile(hist, 0.95) * 1000}

    def _summary(self, start: float, end: float, site: str) -> Dict[str, Any]:
        return self.app.stats.summary(start, end, site, exact_uniq=False)

    # ---------------------------------------------------------------- основной метод
    def evaluate(self, start: float, end: float, site: str = "*") -> Dict[str, Any]:
        key = (int(start) // 15, int(end) // 15, site)
        hit = self._cache.get(key)
        if hit and time.time() - hit[0] < self.CACHE_TTL:
            return hit[1]
        out: List[Dict[str, Any]] = []
        state = self.app.last_applied_state() or self.app.nginx.load_state()
        sites = {str(sid): s for sid, s in state.sites if s.enabled}
        span = max(60.0, end - start)
        recent = end >= time.time() - 120

        def add(sid: str, level: str, site_id: str = "*", summary: str = "", evidence: Any = None,
                value: Any = None, key_extra: str = "") -> None:
            sc = SCENARIOS[sid]
            fid = f"{sid}:{site_id}:{key_extra}"
            now = time.time()
            first = self.first_seen.setdefault(fid, now) if recent else None
            out.append({**scenario_dict(sc), "fid": fid, "level": level, "site": site_id,
                        "site_name": sites[site_id].name if site_id in sites else ("Все сайты" if site_id == "*"
                                                                                   else site_id),
                        "summary": summary, "evidence": evidence, "value": value, "since": first})

        targets = [site] if site != "*" else ["*"] + [sid for sid in sites]
        for s_id in targets:
            cur = self._summary(start, end, s_id)
            self._traffic_rules(add, s_id, cur, start, end, span, sites, recent)
        self._site_config_rules(add, sites if site == "*" else {k: v for k, v in sites.items() if k == site}, start,
                                end)
        if recent:
            self._live_rules(add, site, sites)
        # журнал ошибок nginx — по всему серверу или сайту
        self._errorlog_rules(add, start, end, site)

        if site == "*":
            # находка «по всем сайтам» не нужна, если та же проблема уже показана для конкретных сайтов
            per_site = {f["id"] for f in out if f["site"] != "*"}
            out = [f for f in out if f["site"] != "*" or f["id"] not in per_site or f["group"] in ("server", "data")]
        muted = set(self.app.panel().insights_muted)
        for f in out:
            f["muted"] = f["id"] in muted
        active = [f for f in out if not f["muted"]]
        active.sort(key=lambda f: (-LEVELS[f["level"]], f["group"], f["site"] != "*", f["title"]))
        counts = {lv: sum(1 for f in active if f["level"] == lv) for lv in ("crit", "warn", "info")}
        sysm = dict(self.app.stats.system.latest() or {})
        res = {"findings": active, "muted": [f for f in out if f["muted"]], "counts": counts, "system": sysm,
               "from": start, "to": end, "site": site, "generated": time.time(), "checked": len(SCENARIOS)}
        self._cache[key] = (time.time(), res)
        if len(self._cache) > 64:
            self._cache = dict(sorted(self._cache.items(), key=lambda kv: kv[1][0])[-32:])
        return res

    # ---------------------------------------------------------------- правила по статистике
    def _traffic_rules(self, add, s_id: str, cur: Dict[str, Any], start: float, end: float, span: float,
                       sites: Dict[str, Any], recent: bool) -> None:
        n = cur["requests"]
        codes = {int(k): v for k, v in (cur.get("codes") or {}).items() if str(k).isdigit()}
        st = self.app.stats
        if n >= 50 and cur["err5_pct"] >= 1:
            s5 = sum(v for c, v in codes.items() if 500 <= c < 600)
            dom = sorted(((c, v) for c, v in codes.items() if 500 <= c < 600), key=lambda x: -x[1])
            top = st.tops(start, end, s_id, "e5xx", 5)
            add("e5xx_rate", "crit" if cur["err5_pct"] >= 5 else "warn", s_id,
                f"{cur['err5_pct']:.2f}% ответов — ошибки сервера ({s5} из {n}); "
                + ", ".join(f"{c}: {v}" for c, v in dom[:4]),
                {"columns": ["Адрес", "Ответов"], "rows": [[t["key"], t["count"]] for t in top]}, cur["err5_pct"])
            for code, sid in ((502, "e502"), (504, "e504"), (503, "e503"), (500, "e500")):
                c = codes.get(code, 0)
                if c >= 5 and s5 and c / s5 >= 0.2:
                    rows = [[t["key"].split(" ", 1)[-1], t["count"]] for t in top if t["key"].startswith(f"{code} ")]
                    add(sid, "crit" if cur["err5_pct"] >= 5 else "warn", s_id,
                        f"{c} ответов {code} ({c / s5 * 100:.0f}% всех 5xx)",
                        {"columns": ["Адрес", "Ответов"], "rows": rows} if rows else None, c)
            if s_id != "*" and n >= 20 and cur["err5_pct"] >= 90:
                add("site_down", "crit", s_id, f"{cur['err5_pct']:.0f}% запросов завершились ошибкой 5xx", None,
                    cur["err5_pct"])
        if n >= 100 and cur["err4_pct"] >= 15:
            add("e4xx_rate", "crit" if cur["err4_pct"] >= 35 else "warn", s_id,
                f"{cur['err4_pct']:.1f}% ответов — 4xx; " + ", ".join(
                    f"{c}: {v}" for c, v in sorted(((c, v) for c, v in codes.items() if 400 <= c < 500),
                                                   key=lambda x: -x[1])[:5]), None, cur["err4_pct"])
        if n:
            def share(*cs):
                c = sum(codes.get(x, 0) for x in cs)
                return c, c / n * 100
            e4top = None

            def e4(code: int) -> Optional[Dict[str, Any]]:
                nonlocal e4top
                if e4top is None:
                    e4top = st.tops(start, end, s_id, "e4xx", 30)
                rows = [[t["key"].split(" ", 1)[-1], t["count"]] for t in e4top if t["key"].startswith(f"{code} ")][:6]
                return {"columns": ["Адрес", "Ответов"], "rows": rows} if rows else None
            for code, sid, pct, mn, lvl in ((404, "e404", 5, 20, "warn"), (403, "e403", 3, 20, "warn"),
                                            (429, "e429", 1, 10, "warn"), (401, "e401", 3, 20, "warn"),
                                            (499, "e499", 2, 10, "warn"), (444, "e444", 10, 20, "info")):
                c, p = share(code)
                if c >= mn and p >= pct:
                    add(sid, lvl, s_id, f"{c} ответов {code} ({p:.1f}% запросов)",
                        e4(code) if code not in (444, 499) else None, p)
            c, p = share(413)
            if c:
                add("e413", "warn", s_id, f"{c} запросов отклонено из-за размера тела", e4(413), c)
            c, p = share(400, 414, 431, 494)
            if c >= 10 and p >= 1:
                add("e400", "warn", s_id, f"{c} некорректных запросов ({p:.1f}%)", e4(400), p)
        # производительность
        if n >= 50 and cur["p95"] >= 1000:
            add("latency_p95", "crit" if cur["p95"] >= 3000 else "warn", s_id,
                f"p95 = {cur['p95']:.0f} мс (p50 {cur['p50']:.0f} мс, среднее бэкенда {cur['urt_avg']:.0f} мс)",
                None, cur["p95"])
        if n >= 50 and cur["urt_avg"] >= 500 and cur["rt_avg"] and cur["urt_avg"] >= 0.7 * cur["rt_avg"]:
            top = st.tops(start, end, s_id, "slow", 5)
            add("slow_backend", "crit" if cur["urt_avg"] >= 1500 else "warn", s_id,
                f"бэкенд отвечает в среднем за {cur['urt_avg']:.0f} мс из {cur['rt_avg']:.0f} мс общего времени",
                {"columns": ["Адрес", "Запросов", "Среднее, мс"], "rows": [[t["key"], t["count"], t.get("avg_ms")]
                                                                          for t in top]} if top else None,
                cur["urt_avg"])
        if n >= 50 and cur["urt_avg"] and cur["rt_avg"] >= 2 * cur["urt_avg"] and cur["rt_avg"] - cur["urt_avg"] >= 300:
            add("slow_clients", "info", s_id, f"общее время {cur['rt_avg']:.0f} мс при времени бэкенда "
                                              f"{cur['urt_avg']:.0f} мс", None, cur["rt_avg"] - cur["urt_avg"])
        if n >= 100 and cur.get("slow", 0) / n >= 0.05:
            top = st.tops(start, end, s_id, "slow", 5)
            add("slow_share", "warn", s_id, f"{cur['slow']} медленных запросов ({cur['slow'] / n * 100:.1f}%)",
                {"columns": ["Адрес", "Запросов", "Среднее, мс"], "rows": [[t["key"], t["count"], t.get("avg_ms")]
                                                                          for t in top]} if top else None,
                cur["slow"] / n * 100)
        base = self._baseline(s_id, start)
        if base and base["hours"] >= 6:
            if n >= 50 and base["p95"] and cur["p95"] >= 300 and cur["p95"] >= 2 * base["p95"]:
                add("latency_regression", "warn", s_id,
                    f"p95 {cur['p95']:.0f} мс против {base['p95']:.0f} мс в предыдущие сутки", None, cur["p95"])
            rps = cur["rps"]
            if span >= 600 and base["rps"] >= 0.5 and rps < 0.3 * base["rps"]:
                if s_id != "*" and n == 0 and span >= 1800:
                    add("no_traffic_site", "crit", s_id, f"0 запросов за период; обычно {base['rps']:.2f} в секунду",
                        None, 0)
                else:
                    add("traffic_drop", "crit" if rps < 0.05 * base["rps"] else "warn", s_id,
                        f"{rps:.2f} запросов/с против {base['rps']:.2f} в среднем за прошлые сутки "
                        f"({rps / base['rps'] * 100:.0f}%)", None, rps)
            if rps >= 5 and base["rps"] and rps >= 3 * base["rps"]:
                add("traffic_spike", "warn", s_id, f"{rps:.1f} запросов/с — в {rps / base['rps']:.1f} раза больше "
                                                   f"обычного ({base['rps']:.2f})", None, rps)
        if n >= 300:
            ips = st.tops(start, end, s_id, "ip", 3)
            if ips and ips[0]["count"] / n >= 0.3:
                add("single_ip", "warn", s_id, f"{ips[0]['key']}: {ips[0]['count']} запросов "
                                               f"({ips[0]['count'] / n * 100:.0f}%)",
                    {"columns": ["IP-адрес", "Запросов"], "rows": [[t["key"], t["count"]] for t in ips]},
                    ips[0]["count"] / n * 100, key_extra=ips[0]["key"])
        if n >= 200 and cur.get("bots", 0) / n >= 0.5:
            add("bots_share", "info", s_id, f"{cur['bots'] / n * 100:.0f}% запросов от ботов", None,
                cur["bots"] / n * 100)
        tls = cur.get("tls") or {}
        tls_n = sum(tls.values())
        old = sum(v for k, v in tls.items() if k in ("TLSv1", "TLSv1.1"))
        if tls_n >= 100 and old / tls_n >= 0.01:
            add("tls_legacy", "info", s_id, f"{old} запросов по TLS 1.0/1.1 ({old / tls_n * 100:.1f}%)", None,
                old / tls_n * 100)
        cache = cur.get("cache") or {}
        cache_n = sum(cache.values())
        if s_id in sites:
            s = sites[s_id]
            cache_on = s.cache.enabled or any(lc.enabled and lc.cache == "on" for lc in s.locations)
            if cache_on and cache_n >= 200 and cur["hit_ratio"] < 20:
                add("cache_low_hit", "warn", s_id, f"HIT {cur['hit_ratio']:.0f}% из {cache_n} ответов; "
                    + ", ".join(f"{k}: {v}" for k, v in sorted(cache.items(), key=lambda x: -x[1])[:4]), None,
                    cur["hit_ratio"])
            if (s.type == "proxy" and not cache_on and not s.performance.static_expires and n >= 500
                    and cur.get("static", 0) / n >= 0.4):
                add("static_no_cache", "info", s_id, f"{cur['static'] / n * 100:.0f}% запросов — статика", None,
                    cur["static"] / n * 100)
            if s.ssl.enabled and not s.ssl.force_https and n >= 100 and (n - tls_n) / n >= 0.1:
                add("http_not_redirected", "info", s_id, f"{(n - tls_n) / n * 100:.0f}% запросов по HTTP", None,
                    (n - tls_n) / n * 100)
            if not s.ssl.enabled and n >= 50:
                add("no_https", "warn" if s.type != "redirect" else "info", s_id,
                    f"{n} запросов по незащищённому HTTP за период", None, n)
        if cache_n >= 100:
            stale = cache.get("STALE", 0) + cache.get("UPDATING", 0)
            if stale / cache_n >= 0.05:
                add("cache_stale", "info", s_id, f"{stale} устаревших ответов ({stale / cache_n * 100:.0f}% кэша)",
                    None, stale / cache_n * 100)

    def _site_config_rules(self, add, sites: Dict[str, Any], start: float, end: float) -> None:
        for sid, s in sites.items():
            if s.type != "proxy":
                continue
            prim = [b for b in s.backends if not b.backup and not b.down]
            if len(prim) == 1 and not any(b.backup for b in s.backends):
                add("single_backend", "info", sid, f"бэкенд {prim[0].address}:{prim[0].port} — единственный")
            if not s.health.enabled:
                add("no_healthcheck", "info", sid, "активные проверки выключены")
            if s.ssl.enabled and s.ssl.force_https and not s.ssl.hsts:
                add("no_hsts", "info", sid, "HSTS выключен")

    def _live_rules(self, add, site: str, sites: Dict[str, Any]) -> None:
        app = self.app
        # бэкенды
        groups: Dict[str, List[Any]] = {}
        for t in app.health.targets.values():
            if t.state == "disabled":
                continue
            owner_site = t.owner.split(":")[1] if ":" in t.owner else ""
            if site != "*" and owner_site != site:
                continue
            groups.setdefault(t.owner, []).append(t)
            sid = owner_site if t.owner.startswith(("site:", "loc:")) else "*"
            if t.state == "down":
                add("backend_down", "warn" if t.backup else "crit", sid,
                    f"{t.owner_name}: {t.address}:{t.port} — {t.last_error or 'нет ответа'}", None, 1,
                    key_extra=t.key)
            elif t.state == "up" and t.last_latency >= 0.5:
                add("backend_slow", "crit" if t.last_latency >= 2 else "warn", sid,
                    f"{t.owner_name}: {t.address}:{t.port} отвечает за {t.last_latency * 1000:.0f} мс", None,
                    t.last_latency * 1000, key_extra=t.key)
            if t.checks >= 20:
                up = (t.checks - t.fails) / t.checks * 100
                if 50 <= up < 99:
                    add("backend_unstable", "warn", sid, f"{t.owner_name}: {t.address}:{t.port} — доступность "
                                                         f"{up:.1f}% ({t.fails} неудачных из {t.checks})", None, up,
                        key_extra=t.key)
        for owner, ts in groups.items():
            prim = [t for t in ts if not t.backup]
            if prim and all(t.state == "down" for t in prim):
                sid = owner.split(":")[1] if owner.startswith(("site:", "loc:")) else "*"
                add("backend_all_down", "crit", sid, f"{ts[0].owner_name}: недоступны все {len(prim)} основных "
                                                     f"серверов" + (" (работает резервный)" if any(
                                                         t.backup and t.state == "up" for t in ts) else ""),
                    None, len(prim), key_extra=owner)
        passive = sum(app.stats.agg.passive_upstream.values())
        if site == "*" and passive >= 10:
            add("passive_errors", "warn", "*", f"{passive} ошибок соединения с бэкендами",
                {"columns": ["Бэкенд", "Ошибок"], "rows": [[k, v] for k, v in
                                                           app.stats.agg.passive_upstream.most_common(8)]}, passive)
        if site != "*":
            return
        # nginx и сервер
        if not app.nginx.is_running():
            add("nginx_down", "crit", "*", "мастер-процесс nginx не найден")
        ts, ok, out = app.nginx._last_test
        if ts and not ok:
            add("config_test_failed", "crit", "*", (out or "").strip().splitlines()[-1][:300] if out else "")
        pend = app.pending()
        if pend.get("pending") and not pend.get("error"):
            add("config_pending", "info", "*", f"изменено файлов: {len([x for x in pend.get('changed', []) if not x.endswith('.keep')])}")
        restarts = [t for t in app.nginx_restarts if time.time() - t < 600]
        if restarts:
            add("nginx_restarts", "warn", "*", f"автоматических запусков за 10 минут: {len(restarts)}")
        stub = app.stats.stub.latest()
        if stub.get("ok"):
            cap = self.capacity()
            if stub["active"] >= 0.7 * cap:
                add("conn_capacity", "crit" if stub["active"] >= 0.9 * cap else "warn", "*",
                    f"{stub['active']} соединений из ~{cap} доступных ({stub['active'] / cap * 100:.0f}%)", None,
                    stub["active"])
            if stub.get("dropped", 0) > 0:
                add("conn_dropped", "crit", "*", f"отброшено соединений с запуска nginx: {stub['dropped']}", None,
                    stub["dropped"])
        sysm = app.stats.system.minute_avg(time.time() - 600, time.time()) or app.stats.system.latest() or {}
        if sysm:
            cpu, mem = sysm.get("cpu", 0), sysm.get("mem", 0)
            if cpu >= 80:
                add("cpu_high", "crit" if cpu >= 95 else "warn", "*", f"CPU {cpu:.0f}% в среднем за 10 минут "
                    f"(nginx {sysm.get('nginx_cpu', 0):.0f}%)", None, cpu)
            swap = sysm.get("swap", 0)
            if mem >= 85 or swap >= 20:
                add("mem_high", "crit" if mem >= 95 else "warn", "*", f"память {mem:.0f}%, swap {swap:.0f}%", None,
                    mem)
            latest = app.stats.system.latest() or {}
            disk = max(latest.get("disk", 0), latest.get("disk_log", 0))
            if disk >= 85:
                add("disk_high", "crit" if disk >= 95 else "warn", "*", f"заполнено {disk:.0f}%", None, disk)
            cpus = latest.get("cpus") or 1
            load = sysm.get("load1", 0) / cpus
            if load >= 1.5:
                add("load_high", "crit" if load >= 3 else "warn", "*", f"load {sysm.get('load1', 0):.2f} при {cpus} "
                                                                      f"ядрах ({load:.1f} на ядро)", None, load)
        # сертификаты
        try:
            for c in app.certs.list():
                if not c["used_by"]:
                    continue
                if c["status"] in ("error", "missing", "expired"):
                    add("cert_error", "crit", "*", f"«{c['name']}»: {c.get('last_error') or c['status']}",
                        None, None, key_extra=str(c["id"]))
                elif c["days_left"] is not None and c["days_left"] < 21:
                    add("cert_expiring", "crit" if c["days_left"] < 7 else "warn", "*",
                        f"«{c['name']}» истекает через {max(0, c['days_left']):.0f} дн. (используют: "
                        f"{', '.join(c['used_by'][:3])})" + (f"; последняя ошибка: {c['last_error'][:160]}"
                                                            if c.get("last_error") else ""),
                        None, c["days_left"], key_extra=str(c["id"]))
        except Exception:
            pass
        # блокировки и сборщик
        bs = app.bans.stats()
        if bs["last_error"]:
            add("bans_error", "crit", "*", bs["last_error"][-200:])
        if bs["suspicious"] and not app.panel().autoban_enabled:
            sus = list(app.bans.detector.suspicious.values())[-8:]
            add("scanners", "warn", "*", f"подозрительных адресов: {bs['suspicious']}",
                {"columns": ["IP-адрес", "Правило", "Пример запроса"],
                 "rows": [[x["ip"], x["title"], x.get("sample", "")[:80]] for x in reversed(sus)]}, bs["suspicious"])
        agg = app.stats.agg
        total = agg.parsed + agg.parse_errors
        if total >= 1000 and agg.parse_errors / total >= 0.01:
            add("log_parse_errors", "warn", "*", f"не разобрано {agg.parse_errors} из {total} строк", None,
                agg.parse_errors / total * 100)
        if stub.get("ok") and stub.get("rps", 0) >= 0.2 and time.time() - app.stats.started > 900:
            last = max((t.last_line_ts or 0) for t in app.stats.tailers if t.name == "access") \
                if any(t.name == "access" for t in app.stats.tailers) else 0
            if last and time.time() - last >= 600:
                add("collector_stale", "warn", "*", f"последняя строка журнала доступа — "
                                                    f"{(time.time() - last) / 60:.0f} мин назад", None, None)

    def _errorlog_rules(self, add, start: float, end: float, site: str) -> None:
        q = "SELECT category, COALESCE(NULLIF(site, ''), '*') site, COUNT(*) n FROM errors WHERE ts>=? AND ts<?"
        params: List[Any] = [start, end]
        if site != "*":
            q += " AND site=?"
            params.append(site)
        rows = self.app.db.query(q + " GROUP BY category, 2", params)
        for r in rows:
            cid, n = r["category"], r["n"]
            where_site = r["site"] if site == "*" else site
            info = CATEGORY_INFO.get(cid)
            if not info or f"log_{cid}" not in SCENARIOS:
                continue
            lvl = info["level"]
            if n >= _LOG_MIN.get(lvl, 10):
                sample = self.app.db.one("SELECT message FROM errors WHERE category=? AND ts>=? AND ts<? ORDER BY id "
                                         "DESC LIMIT 1", (cid, start, end))
                add(f"log_{cid}", _LOG_LEVEL.get(lvl, "info"), where_site, f"{n} записей за период",
                    {"columns": ["Последнее сообщение"], "rows": [[(sample or {}).get("message", "")[:300]]]}, n)
